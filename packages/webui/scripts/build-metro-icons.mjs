// Writes the icon stylesheet the web UI ships, from the subset vendored at
// vendor/metro-icons/ (ADR 0032; the-web-ui-wears-more-metro design decision
// "The icon subset is generated, pinned and inlined").
//
// The subset itself is cut out of band, not here: this repository carries the
// finished `icons-subset.woff` and the codepoint of each glyph in it, the way
// the project site carries its own generated subset. A font-subsetting
// library would otherwise sit in the dependency tree of every install, to be
// run twice a year when Metro is upgraded. `vendor/metro-icons/README.md`
// records the command that produced the files.
//
// The standalone server serves only its fixed paths, and a VS Code webview's
// Content Security Policy refuses a font from another origin, so the subset
// is inlined as a `data:` URI rather than shipped as a file.
//
// This script reads nothing under vendor/metro/: that vendored copy is
// build-metro.mjs's own source, and dropping every @font-face there is
// deliberate. The icon face comes from this build, never from that one.
//
// Run: npm run build:metro-icons -w @openspec-ui/webui

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
export const SUBSET_SOURCE = path.resolve(here, "../vendor/metro-icons/icons-subset.woff");
export const CODEPOINTS_SOURCE = path.resolve(here, "../vendor/metro-icons/icons-subset.json");
export const OUTPUT = path.resolve(here, "../src/metro-icons.generated.ts");

/** The font-family the subset is served under, and the prefix every kept
 * glyph's class carries. `src/icons.ts` uses the same prefix to build the
 * class name `iconFor` returns; `icons.test.ts` checks the two agree. */
export const FONT_FAMILY = "openspec-metro-icons";
export const CLASS_PREFIX = "openspec-icon-";

/** The glyphs the shell draws, named as Metro's own `mif-<name>` classes
 * are named, minus the `mif-` prefix. Every value `src/icons.ts`'s `ICONS`
 * map holds names one of these; `icons.test.ts` fails when the two lists
 * disagree in either direction.
 *
 * Adding a name here is not enough on its own: the vendored subset carries
 * only the glyphs it was cut with, so a new name needs the subset cut again
 * by the command in `vendor/metro-icons/README.md`. This script says so
 * rather than silently writing a rule for a glyph the font does not hold. */
export const KEPT_GLYPHS = [
  "git-compare",
  "file-text",
  "archive",
  "check-list",
  "play",
  "stop",
  "refresh",
  "eye",
  "open-in",
  "cog",
  "robot",
  "timeline",
  "warning",
  "checkmark",
];

/**
 * Derives the shipped icon CSS from the vendored subset and its codepoints.
 * Returns the CSS and figures a test and the change's record can state.
 */
export function deriveMetroIconsCss(subsetBuffer, codepoints) {
  const missing = KEPT_GLYPHS.filter((name) => codepoints[name] === undefined);
  if (missing.length > 0) {
    throw new Error(
      `the vendored subset carries no glyph named: ${missing.join(", ")} — cut it again, see vendor/metro-icons/README.md`,
    );
  }
  const spare = Object.keys(codepoints).filter((name) => !KEPT_GLYPHS.includes(name));
  if (spare.length > 0) {
    throw new Error(`the vendored subset carries glyphs nothing names: ${spare.join(", ")}`);
  }

  const dataUri = `data:font/woff;base64,${subsetBuffer.toString("base64")}`;
  const rules = [
    `@font-face{font-family:"${FONT_FAMILY}";src:url(${dataUri}) format("woff");font-weight:400;font-style:normal;font-display:block}`,
    ...KEPT_GLYPHS.map(
      (name) => `.${CLASS_PREFIX}${name}::before{font-family:"${FONT_FAMILY}";content:"\\${codepoints[name]}"}`,
    ),
  ];
  const css = rules.join("\n");
  return { css, figures: { glyphs: KEPT_GLYPHS.length, subsetBytes: subsetBuffer.length, bytes: Buffer.byteLength(css, "utf8") } };
}

/** The module text written to `OUTPUT`. */
export function moduleText(css) {
  return [
    "// GENERATED by packages/webui/scripts/build-metro-icons.mjs from",
    "// packages/webui/vendor/metro-icons/ (Metro UI 5.1.20). Do not edit:",
    "// run `npm run build:metro-icons -w @openspec-ui/webui`. See ADR 0032.",
    "",
    `export const metroIconsCss = ${JSON.stringify(css)};`,
    "",
  ].join("\n");
}

/** The vendored pair, read together so a caller cannot use one without the
 * other. */
export async function readVendoredSubset() {
  const [subsetBuffer, codepointsText] = await Promise.all([
    readFile(SUBSET_SOURCE),
    readFile(CODEPOINTS_SOURCE, "utf8"),
  ]);
  return { subsetBuffer, codepoints: JSON.parse(codepointsText) };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { subsetBuffer, codepoints } = await readVendoredSubset();
  const { css, figures } = deriveMetroIconsCss(subsetBuffer, codepoints);
  await writeFile(OUTPUT, moduleText(css), "utf8");
  console.log(`Wrote ${path.relative(process.cwd(), OUTPUT)}: ${JSON.stringify(figures)}`);
}
